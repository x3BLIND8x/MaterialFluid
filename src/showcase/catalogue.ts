function entry(
  name: string,
  fa: string,
  family: Family,
  en: string,
  persian: string,
  code: string,
  props: PropDoc[] = [],
  states: DemoState[] = [],
  notes?: [string, string],
): Entry {
  return {
    id: name
      .replace(/([A-Z]+)([A-Z][a-z])/g, "$1-$2")
      .replace(/([a-z])([A-Z])/g, "$1-$2")
      .toLowerCase(),
    name,
    fa,
    family,
    description: [en, persian],
    code,
    props: [
      ...(["forms", "navigation", "surfaces", "feedback", "overlays"].includes(family) || ["Toggle", "ToggleGroup", "Checkbox", "RadioGroup", "Switch", "Slider"].includes(name) ? [] : [prop(
        "variant",
        "'filled' | 'tonal' | 'outlined' | 'ghost' | 'danger'",
        "Material action treatment; previous color variants remain supported.",
        "گونه ظاهری دکمه؛ نام‌های قبلی رنگ همچنان پشتیبانی می‌شوند.",
      )]),
      ...(name === "NotificationCenter" ? [] : [prop(
        "size",
        sizesForComponent(name.replace(/([a-z])([A-Z])/g, "$1-$2").toLowerCase()).map(size => `'${size}'`).join(" | "),
        "Small is compact; Medium is the default; Large adds room. Icons and spinners also accept pixel sizes.",
        "کوچک فشرده، متوسط پیش‌فرض و بزرگ جادار است. آیکون و نشانگر چرخان اندازه پیکسلی هم می‌پذیرند.",
      )]),
      ...props.filter((p) => p.name !== "variant" && p.name !== "size"),
    ],
    states,
    notes: notes ?? [
      "Supports keyboard operation and visible focus. Set an accessible label for icon-only actions.",
      "پیمایش با صفحه‌کلید و تمرکز قابل مشاهده پشتیبانی می‌شود. برای دکمه‌های بدون متن، برچسب دسترس‌پذیر تعیین کنید.",
    ],
  };
}
