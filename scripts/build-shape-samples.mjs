// Offline geometry for the existing licensed Material outlines. Run after changing paths.
import { readFile, writeFile } from 'node:fs/promises';
import ts from 'typescript';
import { chromium } from 'playwright';
const source=await readFile(new URL('../src/kit/foundations/material-shapes.ts',import.meta.url),'utf8');
const js=ts.transpileModule(source,{compilerOptions:{target:ts.ScriptTarget.ES2022,module:ts.ModuleKind.ESNext}}).outputText.replaceAll('export ','');
const paths=new Function(`${js}; return shapePaths;`)();
const browser=await chromium.launch({channel:process.env.MF_BROWSER_CHANNEL||'msedge'});
try {
 const page=await browser.newPage();
 const samples=await page.evaluate(paths=>Object.fromEntries(Object.entries(paths).map(([name,d])=>{
  const svg=document.createElementNS('http://www.w3.org/2000/svg','svg'),path=document.createElementNS(svg.namespaceURI,'path');path.setAttribute('d',d);svg.append(path);document.body.append(svg);
  const length=path.getTotalLength(),points=Array.from({length:120},(_,i)=>{const p=path.getPointAtLength(length*i/120);return [Number(p.x.toFixed(4)),Number(p.y.toFixed(4))];});svg.remove();
  const area=points.reduce((sum,[x,y],i)=>{const [nx,ny]=points[(i+1)%points.length];return sum+x*ny-nx*y;},0);
  return [name,area<0?points.reverse():points];
 })),paths);
 await writeFile(new URL('../src/kit/foundations/shape-samples.ts',import.meta.url),`// Generated by scripts/build-shape-samples.mjs from material-shapes.ts.\n// Outlines: Grenish/expressive (MIT) and Android Open Source Project (Apache-2.0).\nimport type { MaterialShapeName } from './material-shapes';\nimport type { Point } from './shape-morph';\nexport const shapeSamples: Record<MaterialShapeName, Point[]> = ${JSON.stringify(samples)};\n`);
 console.log(`Generated ${Object.keys(samples).length} outlines with 120 points each.`);
} finally {await browser.close();}
